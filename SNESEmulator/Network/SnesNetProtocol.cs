    /// <summary>
    /// Lists every message kind understood by the current SnesNet protocol version.
    /// </summary>
    public enum SnesNetMessageType : ushort
    {
        /// <summary>
        /// First client-to-server handshake message containing protocol version,
        /// player name, password, and requested role.
        /// </summary>
        ClientHello = 1,
        /// <summary>
        /// Positive server-to-client handshake response with client id, stream
        /// dimensions, audio sample rate, accepted role, and joystick rights.
        /// </summary>
        ServerWelcome = 2,
        /// <summary>
        /// Negative server-to-client handshake response with a human-readable reason.
        /// </summary>
        ServerReject = 3,
        /// <summary>
        /// Client-to-server joystick state update encoded as active-low Snes bits.
        /// </summary>
        InputState = 4,
        /// <summary>
        /// Server-to-client completed Snes video frame.
        /// </summary>
        VideoFrame = 5,
        /// <summary>
        /// Server-to-client raw PCM audio bytes generated by the host audio engine.
        /// </summary>
        AudioChunk = 6,
        /// <summary>
        /// Server-to-client snapshot of every connected remote client.
        /// </summary>
        ClientList = 7,
        /// <summary>
        /// Server-to-client joystick permission update for the receiving client.
        /// </summary>
        PermissionUpdate = 8,
        /// <summary>
        /// Latency probe. The peer should answer with <see cref="Pong"/>.
        /// </summary>
        Ping = 9,
        /// <summary>
        /// Latency probe response that preserves the original ping timestamp.
        /// </summary>
        Pong = 10,
        /// <summary>
        /// Graceful leave/kick notification.
        /// </summary>
        Disconnect = 11,
        /// <summary>
        /// Server-to-client menu status text shown while the host is paused in a UI overlay.
        /// </summary>
        HostOverlayStatus = 12,
        /// <summary>
        /// Client-to-server keyboard matrix key press or release.
        /// </summary>
        KeyboardInput = 13
    }

