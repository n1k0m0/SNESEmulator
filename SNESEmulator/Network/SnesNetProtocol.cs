        {
            if (width is not (256 or 512) || height is not (224 or 239) || pixels==null || pixels.Length != width * height)
                return EmptyPayload;
            byte[] bytes = new byte[width * height * 4];
            Buffer.BlockCopy(pixels, 0, bytes, 0, bytes.Length);
            return bytes;
        }
