        /// <summary>
        /// Writes one complete framed message to the authenticated transport stream.
        /// </summary>
        /// <param name="stream">Open stream connected to the remote peer.</param>
        /// <param name="message">Message header values and payload to write.</param>
        /// <exception cref="InvalidDataException">
        /// Thrown when the payload exceeds <see cref="MaxPayloadLength"/>.
        /// </exception>
        /// <returns>Number of bytes written to the stream, including the fixed header.</returns>
        public static int WriteMessage(Stream stream, SnesNetMessage message)
        {
            if (stream == null || message == null)
            {
                return 0;
            }

            byte[] payload = message.Payload ?? EmptyPayload;
            if (payload.Length > MaxPayloadLength)
            {
                throw new InvalidDataException("SnesNet payload is too large.");
            }

            // TCP is a byte stream, so every protocol message starts with a small
            // fixed header that tells the receiver how many payload bytes to read next.
            byte[] header = new byte[HeaderLength];
            WriteInt32(header, 0, payload.Length);
            WriteUInt16(header, 4, (ushort)message.Type);
            WriteUInt16(header, 6, message.Flags);
            WriteUInt32(header, 8, message.Sequence);
            WriteInt64(header, 12, message.Timestamp);
            stream.Write(header, 0, header.Length);
            if (payload.Length > 0)
            {
                // Payloads are already fully serialized by the message-specific helpers.
                stream.Write(payload, 0, payload.Length);
            }

            message.WireLength = HeaderLength + payload.Length;
            return message.WireLength;
        }

        /// <summary>
        /// Reads one complete framed message from the authenticated transport stream.
        /// </summary>
        /// <param name="stream">Open stream connected to the remote peer.</param>
        /// <returns>The decoded message, or null when the peer closes the stream.</returns>
        /// <exception cref="InvalidDataException">
        /// Thrown when the remote peer announces an invalid payload length.
        /// </exception>
        public static SnesNetMessage ReadMessage(Stream stream)
        {
            if (stream == null)
            {
                return null;
            }

            byte[] header = new byte[HeaderLength];
            if (!ReadExact(stream, header, 0, header.Length))
            {
                // A short header means the peer disconnected cleanly or the socket died.
                return null;
            }

            int payloadLength = ReadInt32(header, 0);
            if (payloadLength < 0 || payloadLength > MaxPayloadLength)
            {
                throw new InvalidDataException("Invalid SnesNet payload length.");
            }

            byte[] payload = payloadLength == 0 ? EmptyPayload : new byte[payloadLength];
            if (payloadLength > 0 && !ReadExact(stream, payload, 0, payloadLength))
            {
                // The frame header was valid, but the peer closed before the body arrived.
                return null;
            }

            return new SnesNetMessage
            {
                Type = (SnesNetMessageType)ReadUInt16(header, 4),
                Flags = ReadUInt16(header, 6),
                Sequence = ReadUInt32(header, 8),
                Timestamp = ReadInt64(header, 12),
                Payload = payload,
                WireLength = HeaderLength + payloadLength
            };
        }

        /// <summary>
        /// Builds a ClientHello payload for the initial client-to-host handshake.
        /// </summary>
        /// <param name="name">Player name shown in the host client list.</param>
        /// <param name="password">Plain-text session password entered in the network menu.</param>
        /// <param name="role">Requested role. The server still decides joystick rights.</param>
        /// <returns>Serialized handshake payload.</returns>
        public static byte[] CreateClientHelloPayload(string name, string password, SnesNetClientRole role)
        {
            using (var stream = new MemoryStream())
            using (var writer = new BinaryWriter(stream, Encoding.UTF8))
            {
                // Version goes first so the host can reject incompatible clients before
                // interpreting later fields.
                writer.Write(Version);
                WriteString(writer, name);
                WriteString(writer, password);
                writer.Write((byte)role);
                return stream.ToArray();
            }
        }

        /// <summary>
        /// Parses a ClientHello payload received by the server.
        /// </summary>
        /// <param name="payload">Serialized payload from the message body.</param>
        /// <param name="version">Decoded protocol version.</param>
        /// <param name="name">Decoded player name.</param>
        /// <param name="password">Decoded session password.</param>
        /// <param name="role">Decoded requested role.</param>
        public static void ReadClientHelloPayload(byte[] payload, out int version, out string name, out string password, out SnesNetClientRole role)
        {
            using (var stream = new MemoryStream(payload ?? EmptyPayload))
            using (var reader = new BinaryReader(stream, Encoding.UTF8))
            {
                version = reader.ReadInt32();
                name = ReadString(reader);
                password = ReadString(reader);
                role = (SnesNetClientRole)reader.ReadByte();
            }
        }

        /// <summary>
        /// Builds a ServerWelcome payload for an accepted client.
        /// </summary>
        /// <param name="clientId">Host-assigned session-local client id.</param>
        /// <param name="width">Remote framebuffer width in pixels.</param>
        /// <param name="height">Remote framebuffer height in pixels.</param>
        /// <param name="audioSampleRate">PCM audio sample rate used for AudioChunk messages.</param>
        /// <param name="role">Accepted role.</param>
        /// <param name="permission">Initial joystick permission.</param>
        /// <param name="keyboardEnabled">Initial keyboard permission.</param>
        /// <param name="status">Human-readable connection status text.</param>
        /// <returns>Serialized welcome payload.</returns>
        public static byte[] CreateServerWelcomePayload(int clientId, int width, int height, int audioSampleRate, SnesNetClientRole role, SnesNetJoystickPermission permission, bool keyboardEnabled, string status)
        {
            using (var stream = new MemoryStream())
            using (var writer = new BinaryWriter(stream, Encoding.UTF8))
            {
                // Dimensions are part of the handshake because the client disables its
                // local emulator and sizes the remote frame buffer from this metadata.
                writer.Write(clientId);
                writer.Write(width);
                writer.Write(height);
                writer.Write(audioSampleRate);
                writer.Write((byte)role);
                writer.Write((byte)permission);
                writer.Write(keyboardEnabled);
                WriteString(writer, status);
                return stream.ToArray();
            }
        }

        /// <summary>
        /// Parses a ServerWelcome payload received by a client.
        /// </summary>
        /// <param name="payload">Serialized payload from the message body.</param>
        /// <param name="clientId">Decoded host-assigned client id.</param>
        /// <param name="width">Decoded remote framebuffer width.</param>
        /// <param name="height">Decoded remote framebuffer height.</param>
        /// <param name="audioSampleRate">Decoded remote audio sample rate.</param>
        /// <param name="role">Decoded accepted role.</param>
        /// <param name="permission">Decoded initial joystick permission.</param>
        /// <param name="keyboardEnabled">Decoded initial keyboard permission.</param>
        /// <param name="status">Decoded welcome status text.</param>
        public static void ReadServerWelcomePayload(byte[] payload, out int clientId, out int width, out int height, out int audioSampleRate, out SnesNetClientRole role, out SnesNetJoystickPermission permission, out bool keyboardEnabled, out string status)
        {
            using (var stream = new MemoryStream(payload ?? EmptyPayload))
            using (var reader = new BinaryReader(stream, Encoding.UTF8))
            {
                clientId = reader.ReadInt32();
                width = reader.ReadInt32();
                height = reader.ReadInt32();
                audioSampleRate = reader.ReadInt32();
                role = (SnesNetClientRole)reader.ReadByte();
                permission = (SnesNetJoystickPermission)reader.ReadByte();
                keyboardEnabled = reader.ReadBoolean();
                status = ReadString(reader);
            }
        }

        /// <summary>
        /// Builds a text-only payload used by status, reject, disconnect, and popup messages.
        /// </summary>
        /// <param name="text">Text to serialize as UTF-8.</param>
        /// <returns>Serialized text payload.</returns>
        public static byte[] CreateTextPayload(string text)
        {
            using (var stream = new MemoryStream())
            using (var writer = new BinaryWriter(stream, Encoding.UTF8))
            {
                WriteString(writer, text);
                return stream.ToArray();
            }
        }

        /// <summary>
        /// Reads a text-only payload.
        /// </summary>
        /// <param name="payload">Serialized text payload.</param>
        /// <returns>Decoded UTF-8 text, or an empty string for an empty payload.</returns>
        public static string ReadTextPayload(byte[] payload)
        {
            using (var stream = new MemoryStream(payload ?? EmptyPayload))
            using (var reader = new BinaryReader(stream, Encoding.UTF8))
            {
                return ReadString(reader);
            }
        }

        // Two active-low bytes; bits 4-15 represent all twelve SNES buttons.
        public static byte[] CreateInputStatePayload(ushort activeLowJoystickState)
        {
            return new[] { (byte)activeLowJoystickState, (byte)(activeLowJoystickState >> 8) };
        }

        /// <summary>
        /// Reads an input-state payload.
        /// </summary>
        /// <param name="payload">Serialized input payload.</param>
        /// <returns>Active-low joystick state, neutral when the payload is missing.</returns>
        public static ushort ReadInputStatePayload(byte[] payload)
        {
            return payload != null && payload.Length == 2 ? (ushort)((payload[0] | payload[1] << 8) | 15) : (ushort)0xFFFF;
        }

        /// <summary>
        /// Builds a keyboard-input payload from a frontend key and press state.
        /// </summary>
        /// <param name="key">Frontend key understood by the reserved keyboard input extension.</param>
        /// <param name="pressed">True for key down, false for key up.</param>
        /// <returns>Serialized keyboard event.</returns>
        public static byte[] CreateKeyboardInputPayload(Key key, bool pressed)
        {
            using (var stream = new MemoryStream())
            using (var writer = new BinaryWriter(stream, Encoding.UTF8))
            {
                writer.Write((int)key);
                writer.Write(pressed);
                return stream.ToArray();
            }
        }

        /// <summary>
        /// Reads a keyboard-input payload.
        /// </summary>
        /// <param name="payload">Serialized keyboard event.</param>
        /// <param name="key">Decoded frontend key.</param>
        /// <param name="pressed">Decoded press state.</param>
        /// <returns>True when the payload was well-formed.</returns>
        public static bool ReadKeyboardInputPayload(byte[] payload, out Key key, out bool pressed)
        {
            key = default(Key);
            pressed = false;
            if (payload == null || payload.Length < 5)
            {
                return false;
            }

            using (var stream = new MemoryStream(payload))
            using (var reader = new BinaryReader(stream, Encoding.UTF8))
            {
                key = (Key)reader.ReadInt32();
                pressed = reader.ReadBoolean();
                return true;
            }
        }

        /// <summary>
        /// Packs ARGB32 emulator pixels into the full-color SNES ARGB format used on the wire.
        /// </summary>
        /// <param name="pixels">Source ARGB32 pixels from the host completed framebuffer.</param>
        /// <param name="width">Source frame width.</param>
        /// <param name="height">Source frame height.</param>
        /// <returns>Four bytes per pixel, or an empty array for invalid input.</returns>
        public static byte[] CreatePackedVideoFrame(uint[] pixels, int width, int height)
        {
            if (width < 1 || width > 512 || height < 1 || height > 478 || pixels.Length < width * height)
                return EmptyPayload;
            byte[] bytes = new byte[width * height * 4];
            Buffer.BlockCopy(pixels, 0, bytes, 0, bytes.Length);
            return bytes;
        }
        public static bool PackedVideoFramesEqual(byte[] a, byte[] b) => a != null && b != null && a.AsSpan().SequenceEqual(b);
        public static byte[] CreateVideoFramePayload(uint[] pixels, int width, int height, long frameId)
            => CreateBestVideoFramePayload(CreatePackedVideoFrame(pixels, width, height), null, width, height, frameId, 0, out _);
        public static byte[] CreateBestVideoFramePayload(byte[] pixels, byte[] previous, int width, int height, long frameId, long previousFrameId, out bool usedDelta)
        {
            usedDelta = false;
            using var output = new MemoryStream();
            using var writer = new BinaryWriter(output);
            writer.Write(width); writer.Write(height); writer.Write(frameId); writer.Write(pixels.Length);
            writer.Flush();
            using (var deflate = new DeflateStream(output, CompressionLevel.Fastest, true)) deflate.Write(pixels);
            return output.ToArray();
        }
        public static SnesNetVideoFrame ReadVideoFramePayload(byte[] payload)
        {
            byte[] reference = null; long id = 0;
            return ReadVideoFramePayload(payload, ref reference, ref id, null);
        }
        public static SnesNetVideoFrame ReadVideoFramePayload(byte[] payload, ref byte[] reference, ref long id)
            => ReadVideoFramePayload(payload, ref reference, ref id, null);
        public static SnesNetVideoFrame ReadVideoFramePayload(byte[] payload, ref byte[] reference, ref long id, uint[] target)
        {
            if (payload == null || payload.Length < 20) return null;
            using var input = new MemoryStream(payload);
            using var reader = new BinaryReader(input);
            int width = reader.ReadInt32(), height = reader.ReadInt32();
            long frameId = reader.ReadInt64(); int size = reader.ReadInt32();
            if (width < 1 || width > 512 || height < 1 || height > 478 || size != width * height * 4) return null;
            byte[] bytes = new byte[size];
            using var deflate = new DeflateStream(input, CompressionMode.Decompress);
            try { deflate.ReadExactly(bytes); if (deflate.ReadByte() != -1) return null; }
            catch (InvalidDataException) { return null; }
            catch (EndOfStreamException) { return null; }
            uint[] pixels = target != null && target.Length == width * height ? target : new uint[width * height];
            Buffer.BlockCopy(bytes, 0, pixels, 0, size);
            reference = bytes; id = frameId;
            return new SnesNetVideoFrame { Width = width, Height = height, FrameId = frameId, Pixels = pixels };
        }

        public static byte[] CreateAudioChunkPayload(byte[] buffer, int count, int sampleRate)
        {
            if (buffer == null || count <= 0)
            {
                return EmptyPayload;
            }

            count = Math.Min(count, buffer.Length);
            count -= count % 2;
            if (count <= 0)
            {
                return EmptyPayload;
            }

            byte[] rawPayload = CreateRawAudioChunkPayload(buffer, count, sampleRate);
            byte[] adpcmBytes = EncodeImaAdpcmBlock(buffer, count);
            if (adpcmBytes == null || adpcmBytes.Length == 0)
            {
                return rawPayload;
            }

            byte[] adpcmPayload = new byte[16 + adpcmBytes.Length];
            // Store the sample rate with every chunk so clients can validate that
            // their audio output still matches the host stream.
            WriteInt32(adpcmPayload, 0, sampleRate);
            WriteInt32(adpcmPayload, 4, AudioFormatImaAdpcm4);
            WriteInt32(adpcmPayload, 8, count);
            WriteInt32(adpcmPayload, 12, adpcmBytes.Length);
            Buffer.BlockCopy(adpcmBytes, 0, adpcmPayload, 16, adpcmBytes.Length);
            return adpcmPayload.Length + MinimumCompressionSavings < rawPayload.Length
                ? adpcmPayload
                : rawPayload;
        }

        /// <summary>
        /// Parses a raw PCM or self-contained ADPCM audio chunk payload.
        /// </summary>
        /// <param name="payload">Serialized audio payload.</param>
        /// <param name="sampleRate">Decoded PCM sample rate.</param>
        /// <param name="buffer">Decoded PCM buffer.</param>
        /// <param name="count">Number of valid bytes in <paramref name="buffer"/>.</param>
        /// <returns>True when the payload is valid and audio bytes were decoded.</returns>
        public static bool ReadAudioChunkPayload(byte[] payload, out int sampleRate, out byte[] buffer, out int count)
        {
            sampleRate = DefaultAudioSampleRate;
            buffer = EmptyPayload;
            count = 0;
            if (payload == null || payload.Length < 8)
            {
                return false;
            }

            sampleRate = ReadInt32(payload, 0);
            int formatOrCount = ReadInt32(payload, 4);
            if (payload.Length >= 16 && (formatOrCount == AudioFormatPcm16 || formatOrCount == AudioFormatImaAdpcm4))
            {
                int decodedCount = ReadInt32(payload, 8);
                int encodedCount = ReadInt32(payload, 12);
                if (sampleRate <= 0 || decodedCount <= 0 || encodedCount <= 0 || payload.Length < 16 + encodedCount)
                {
                    count = 0;
                    return false;
                }

                if (formatOrCount == AudioFormatPcm16)
                {
                    if (decodedCount != encodedCount)
                    {
                        count = 0;
                        return false;
                    }

                    buffer = new byte[decodedCount];
                    Buffer.BlockCopy(payload, 16, buffer, 0, decodedCount);
                    count = decodedCount;
                    return true;
                }

                buffer = DecodeImaAdpcmBlock(payload, 16, encodedCount, decodedCount);
                if (buffer == null)
                {
                    buffer = EmptyPayload;
                    count = 0;
                    return false;
                }

                count = buffer.Length;
                return true;
            }

            count = formatOrCount;
            if (sampleRate <= 0 || count <= 0 || payload.Length < 8 + count)
            {
                // Invalid chunks are ignored instead of tearing down the whole session;
                // video and control traffic can keep going.
                count = 0;
                return false;
            }

            buffer = new byte[count];
            Buffer.BlockCopy(payload, 8, buffer, 0, count);
            return true;
        }

        /// <summary>
        /// Builds the legacy raw PCM audio payload used as the lossless fallback.
        /// </summary>
        /// <param name="buffer">Little-endian 16-bit mono PCM bytes.</param>
        /// <param name="count">Even number of valid PCM bytes.</param>
        /// <param name="sampleRate">PCM sample rate for this chunk.</param>
        /// <returns>Serialized raw PCM audio payload.</returns>
        private static byte[] CreateRawAudioChunkPayload(byte[] buffer, int count, int sampleRate)
        {
            byte[] payload = new byte[8 + count];
            WriteInt32(payload, 0, sampleRate);
            WriteInt32(payload, 4, count);
            Buffer.BlockCopy(buffer, 0, payload, 8, count);
            return payload;
        }

        /// <summary>
        /// Encodes one independent 16-bit PCM block as 4-bit IMA ADPCM.
        /// </summary>
        /// <param name="buffer">Little-endian source PCM.</param>
        /// <param name="count">Even number of source bytes.</param>
        /// <returns>ADPCM block with predictor and step-index seed, or null for invalid input.</returns>
        private static byte[] EncodeImaAdpcmBlock(byte[] buffer, int count)
        {
            if (buffer == null || count <= 0 || (count & 1) != 0 || buffer.Length < count)
            {
                return null;
            }

            int sampleCount = count / 2;
            int predictor = ReadInt16(buffer, 0);
            int stepIndex = EstimateImaAdpcmInitialIndex(buffer, count);
            int nibbleCount = Math.Max(0, sampleCount - 1);
            byte[] encoded = new byte[4 + ((nibbleCount + 1) / 2)];
            WriteInt16(encoded, 0, (short)predictor);
            encoded[2] = (byte)stepIndex;
            encoded[3] = 0;

            for (int sampleIndex = 1; sampleIndex < sampleCount; sampleIndex++)
            {
                int nibbleIndex = sampleIndex - 1;
                int sample = ReadInt16(buffer, sampleIndex * 2);
                int nibble = EncodeImaAdpcmNibble(sample, ref predictor, ref stepIndex);
                int packedOffset = 4 + (nibbleIndex / 2);
                if ((nibbleIndex & 1) == 0)
                {
                    encoded[packedOffset] = (byte)(nibble & 0x0F);
                }
                else
                {
                    encoded[packedOffset] |= (byte)((nibble & 0x0F) << 4);
                }
            }

            return encoded;
        }

        /// <summary>
        /// Decodes one independent 4-bit IMA ADPCM block back to little-endian PCM.
        /// </summary>
        /// <param name="buffer">Payload buffer containing the encoded block.</param>
        /// <param name="offset">Encoded block offset.</param>
        /// <param name="count">Encoded block byte count.</param>
        /// <param name="decodedCount">Expected decoded PCM byte count.</param>
        /// <returns>Decoded PCM bytes, or null when the block is malformed.</returns>
        private static byte[] DecodeImaAdpcmBlock(byte[] buffer, int offset, int count, int decodedCount)
        {
            if (buffer == null || offset < 0 || count < 4 || decodedCount <= 0 || (decodedCount & 1) != 0 || offset > buffer.Length - count)
            {
                return null;
            }

            int sampleCount = decodedCount / 2;
            int expectedEncodedCount = 4 + (Math.Max(0, sampleCount - 1) + 1) / 2;
            if (count != expectedEncodedCount)
            {
                return null;
            }

            int predictor = ReadInt16(buffer, offset);
            int stepIndex = buffer[offset + 2];
            if (stepIndex < 0 || stepIndex >= ImaAdpcmStepTable.Length)
            {
                return null;
            }

            byte[] decoded = new byte[decodedCount];
            WriteInt16(decoded, 0, (short)predictor);
            for (int sampleIndex = 1; sampleIndex < sampleCount; sampleIndex++)
            {
                int nibbleIndex = sampleIndex - 1;
                int packed = buffer[offset + 4 + (nibbleIndex / 2)];
                int nibble = (nibbleIndex & 1) == 0
                    ? packed & 0x0F
                    : (packed >> 4) & 0x0F;
                DecodeImaAdpcmNibble(nibble, ref predictor, ref stepIndex);
                WriteInt16(decoded, sampleIndex * 2, (short)predictor);
            }

            return decoded;
        }

        /// <summary>
        /// Chooses an initial IMA step index for a self-contained audio block.
        /// </summary>
        /// <param name="buffer">Little-endian source PCM.</param>
        /// <param name="count">Even number of source bytes.</param>
        /// <returns>Step table index matching the first sample transition.</returns>
        private static int EstimateImaAdpcmInitialIndex(byte[] buffer, int count)
        {
            if (count < 4)
            {
                return 0;
            }

            int first = ReadInt16(buffer, 0);
            int second = ReadInt16(buffer, 2);
            int difference = Math.Abs(second - first);
            int index = 0;
            while (index + 1 < ImaAdpcmStepTable.Length && ImaAdpcmStepTable[index + 1] <= Math.Max(7, difference))
            {
                index++;
            }

            return index;
        }

        /// <summary>
        /// Encodes one PCM sample into an IMA ADPCM nibble and advances encoder state.
        /// </summary>
        /// <param name="sample">Target PCM sample.</param>
        /// <param name="predictor">Current predictor, updated to the decoded approximation.</param>
        /// <param name="stepIndex">Current step-table index, updated after the nibble.</param>
        /// <returns>4-bit ADPCM code.</returns>
        private static int EncodeImaAdpcmNibble(int sample, ref int predictor, ref int stepIndex)
        {
            int step = ImaAdpcmStepTable[stepIndex];
            int difference = sample - predictor;
            int nibble = 0;
            if (difference < 0)
            {
                nibble = 8;
                difference = -difference;
            }

            int remaining = difference;
            if (remaining >= step)
            {
                nibble |= 4;
                remaining -= step;
            }

            if (remaining >= step / 2)
            {
                nibble |= 2;
                remaining -= step / 2;
            }

            if (remaining >= step / 4)
            {
                nibble |= 1;
            }

            DecodeImaAdpcmNibble(nibble, ref predictor, ref stepIndex);
            return nibble;
        }

        /// <summary>
        /// Applies one IMA ADPCM nibble to the decoder state.
        /// </summary>
        /// <param name="nibble">4-bit ADPCM code.</param>
        /// <param name="predictor">Current predictor, updated in place.</param>
        /// <param name="stepIndex">Current step-table index, updated in place.</param>
        private static void DecodeImaAdpcmNibble(int nibble, ref int predictor, ref int stepIndex)
        {
            int step = ImaAdpcmStepTable[stepIndex];
            int difference = step >> 3;
            if ((nibble & 4) != 0)
            {
                difference += step;
            }

            if ((nibble & 2) != 0)
            {
                difference += step >> 1;
            }

            if ((nibble & 1) != 0)
            {
                difference += step >> 2;
            }

            predictor = (nibble & 8) != 0
                ? ClampToInt16(predictor - difference)
                : ClampToInt16(predictor + difference);
            stepIndex += ImaAdpcmIndexTable[nibble & 0x0F];
            if (stepIndex < 0)
            {
                stepIndex = 0;
            }
            else if (stepIndex >= ImaAdpcmStepTable.Length)
            {
                stepIndex = ImaAdpcmStepTable.Length - 1;
            }
        }

        /// <summary>
        /// Builds a client-list payload for the host's network client overview.
        /// </summary>
        /// <param name="clients">Current snapshot list to broadcast.</param>
        /// <returns>Serialized list payload.</returns>
        public static byte[] CreateClientListPayload(IList<SnesNetClientSnapshot> clients)
        {
            using (var stream = new MemoryStream())
            using (var writer = new BinaryWriter(stream, Encoding.UTF8))
            {
                int count = clients == null ? 0 : clients.Count;
                writer.Write(count);
                for (int index = 0; index < count; index++)
                {
                    SnesNetClientSnapshot client = clients[index];
                    // Keep this structure intentionally flat. It is cheap to parse and
                    // mirrors exactly what the overlay needs to display.
                    writer.Write(client.ClientId);
                    WriteString(writer, client.Name);
                    WriteString(writer, client.RemoteAddress);
                    WriteString(writer, client.RemoteEndpoint);
                    writer.Write((byte)client.Role);
                    writer.Write((byte)client.Permission);
                    writer.Write(client.KeyboardEnabled);
                    writer.Write(client.JoystickState);
                    writer.Write(client.LatencyMilliseconds);
                    writer.Write(client.Connected);
                }

                return stream.ToArray();
            }
        }

        /// <summary>
        /// Parses a client-list payload.
        /// </summary>
        /// <param name="payload">Serialized list payload.</param>
        /// <returns>Decoded client snapshots.</returns>
        public static List<SnesNetClientSnapshot> ReadClientListPayload(byte[] payload)
        {
            var clients = new List<SnesNetClientSnapshot>();
            using (var stream = new MemoryStream(payload ?? EmptyPayload))
            using (var reader = new BinaryReader(stream, Encoding.UTF8))
            {
                int count = reader.ReadInt32();
                for (int index = 0; index < count; index++)
                {
                    clients.Add(new SnesNetClientSnapshot
                    {
                        ClientId = reader.ReadInt32(),
                        Name = ReadString(reader),
                        RemoteAddress = ReadString(reader),
                        RemoteEndpoint = ReadString(reader),
                        Role = (SnesNetClientRole)reader.ReadByte(),
                        Permission = (SnesNetJoystickPermission)reader.ReadByte(),
                        KeyboardEnabled = reader.ReadBoolean(),
                        JoystickState = reader.ReadUInt16(),
                        LatencyMilliseconds = reader.ReadInt32(),
                        Connected = reader.ReadBoolean()
                    });
                }
            }

            return clients;
        }

        /// <summary>
        /// Builds a permission-update payload.
        /// </summary>
        /// <param name="permission">Host-granted joystick permission.</param>
        /// <param name="keyboardEnabled">Host-granted keyboard permission.</param>
        /// <returns>Serialized permission payload.</returns>
        public static byte[] CreatePermissionPayload(SnesNetJoystickPermission permission, bool keyboardEnabled)
        {
            return new[] { (byte)permission, (byte)(keyboardEnabled ? 1 : 0) };
        }

        /// <summary>
        /// Reads a permission-update payload.
        /// </summary>
        /// <param name="payload">Serialized permission payload.</param>
        /// <param name="permission">Decoded joystick permission.</param>
        /// <param name="keyboardEnabled">Decoded keyboard permission.</param>
        public static void ReadPermissionPayload(byte[] payload, out SnesNetJoystickPermission permission, out bool keyboardEnabled)
        {
            permission = payload != null && payload.Length > 0
                ? (SnesNetJoystickPermission)payload[0]
                : SnesNetJoystickPermission.Observer;
            keyboardEnabled = payload != null && payload.Length > 1 && payload[1] != 0;
        }

        /// <summary>
        /// Reads exactly the requested number of bytes unless the stream closes.
        /// </summary>
        /// <param name="stream">Source stream.</param>
        /// <param name="buffer">Destination buffer.</param>
        /// <param name="offset">Destination offset.</param>
        /// <param name="count">Number of bytes to read.</param>
        /// <returns>True when all bytes were read; false when the stream ended early.</returns>
        private static bool ReadExact(Stream stream, byte[] buffer, int offset, int count)
        {
            while (count > 0)
            {
                int read = stream.Read(buffer, offset, count);
                if (read <= 0)
                {
                    return false;
                }

                // Stream.Read can return partial data even when the connection is
                // healthy, so keep going until this frame fragment is complete.
                offset += read;
                count -= read;
            }

            return true;
        }

        /// <summary>
        /// Writes a length-prefixed UTF-8 string to a binary payload.
        /// </summary>
        /// <param name="writer">Payload writer.</param>
        /// <param name="value">String value to write; null becomes empty.</param>
        private static void WriteString(BinaryWriter writer, string value)
        {
            byte[] bytes = Encoding.UTF8.GetBytes(value ?? string.Empty);
            writer.Write(bytes.Length);
            writer.Write(bytes);
        }

        /// <summary>
        /// Reads a length-prefixed UTF-8 string from a binary payload.
        /// </summary>
        /// <param name="reader">Payload reader.</param>
        /// <returns>Decoded string.</returns>
        /// <exception cref="InvalidDataException">Thrown when the encoded string length is invalid.</exception>
        private static string ReadString(BinaryReader reader)
        {
            int length = reader.ReadInt32();
            if (length < 0 || length > 65536)
            {
                throw new InvalidDataException("Invalid SnesNet string length.");
            }

            byte[] bytes = reader.ReadBytes(length);
            return Encoding.UTF8.GetString(bytes);
        }

        /// <summary>
        /// Writes an unsigned 16-bit integer using little-endian byte order.
        /// </summary>
        /// <param name="buffer">Destination buffer.</param>
        /// <param name="offset">Destination offset.</param>
        /// <param name="value">Value to write.</param>
        private static void WriteUInt16(byte[] buffer, int offset, ushort value)
        {
            buffer[offset] = (byte)(value & 0xFF);
            buffer[offset + 1] = (byte)((value >> 8) & 0xFF);
        }

        /// <summary>
        /// Reads an unsigned 16-bit integer using little-endian byte order.
        /// </summary>
        /// <param name="buffer">Source buffer.</param>
        /// <param name="offset">Source offset.</param>
        /// <returns>Decoded value.</returns>
        private static ushort ReadUInt16(byte[] buffer, int offset)
        {
            return (ushort)(buffer[offset] | (buffer[offset + 1] << 8));
        }

        /// <summary>
        /// Writes a signed 16-bit integer using little-endian byte order.
        /// </summary>
        /// <param name="buffer">Destination buffer.</param>
        /// <param name="offset">Destination offset.</param>
        /// <param name="value">Value to write.</param>
        private static void WriteInt16(byte[] buffer, int offset, short value)
        {
            WriteUInt16(buffer, offset, unchecked((ushort)value));
        }

        /// <summary>
        /// Reads a signed 16-bit integer using little-endian byte order.
        /// </summary>
        /// <param name="buffer">Source buffer.</param>
        /// <param name="offset">Source offset.</param>
        /// <returns>Decoded value.</returns>
        private static short ReadInt16(byte[] buffer, int offset)
        {
            return unchecked((short)ReadUInt16(buffer, offset));
        }

        /// <summary>
        /// Writes a signed 32-bit integer using little-endian byte order.
        /// </summary>
        /// <param name="buffer">Destination buffer.</param>
        /// <param name="offset">Destination offset.</param>
        /// <param name="value">Value to write.</param>
        private static void WriteInt32(byte[] buffer, int offset, int value)
        {
            WriteUInt32(buffer, offset, unchecked((uint)value));
        }

        /// <summary>
        /// Reads a signed 32-bit integer using little-endian byte order.
        /// </summary>
        /// <param name="buffer">Source buffer.</param>
        /// <param name="offset">Source offset.</param>
        /// <returns>Decoded value.</returns>
        private static int ReadInt32(byte[] buffer, int offset)
        {
            return unchecked((int)ReadUInt32(buffer, offset));
        }

        /// <summary>
        /// Writes an unsigned 32-bit integer using little-endian byte order.
        /// </summary>
        /// <param name="buffer">Destination buffer.</param>
        /// <param name="offset">Destination offset.</param>
        /// <param name="value">Value to write.</param>
        private static void WriteUInt32(byte[] buffer, int offset, uint value)
        {
            buffer[offset] = (byte)(value & 0xFF);
            buffer[offset + 1] = (byte)((value >> 8) & 0xFF);
            buffer[offset + 2] = (byte)((value >> 16) & 0xFF);
            buffer[offset + 3] = (byte)((value >> 24) & 0xFF);
        }

        /// <summary>
        /// Reads an unsigned 32-bit integer using little-endian byte order.
        /// </summary>
        /// <param name="buffer">Source buffer.</param>
        /// <param name="offset">Source offset.</param>
        /// <returns>Decoded value.</returns>
        private static uint ReadUInt32(byte[] buffer, int offset)
        {
            return
                (uint)(buffer[offset] |
                (buffer[offset + 1] << 8) |
                (buffer[offset + 2] << 16) |
                (buffer[offset + 3] << 24));
        }

        /// <summary>
        /// Writes a signed 64-bit integer using little-endian byte order.
        /// </summary>
        /// <param name="buffer">Destination buffer.</param>
        /// <param name="offset">Destination offset.</param>
        /// <param name="value">Value to write.</param>
        private static void WriteInt64(byte[] buffer, int offset, long value)
        {
            ulong unsigned = unchecked((ulong)value);
            for (int index = 0; index < 8; index++)
            {
                buffer[offset + index] = (byte)((unsigned >> (index * 8)) & 0xFF);
            }
        }

        /// <summary>
        /// Reads a signed 64-bit integer using little-endian byte order.
        /// </summary>
        /// <param name="buffer">Source buffer.</param>
        /// <param name="offset">Source offset.</param>
        /// <returns>Decoded value.</returns>
        private static long ReadInt64(byte[] buffer, int offset)
        {
            ulong value = 0;
            for (int index = 0; index < 8; index++)
            {
                value |= ((ulong)buffer[offset + index]) << (index * 8);
            }

            return unchecked((long)value);
        }

        /// <summary>
        /// Clamps an integer to the signed 16-bit PCM sample range.
        /// </summary>
        /// <param name="value">Value to clamp.</param>
        /// <returns>Clamped PCM sample value.</returns>
        private static int ClampToInt16(int value)
        {
            if (value < short.MinValue)
            {
                return short.MinValue;
            }

            if (value > short.MaxValue)
            {
                return short.MaxValue;
            }

            return value;
        }
    }
