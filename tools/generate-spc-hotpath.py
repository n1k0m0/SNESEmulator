#!/usr/bin/env python3
"""Generate the bounded SPC700 hot-path CFG; run --check in validation.

The normal decoder remains the authority for unsupported opcodes. Each emitted
bus operation has its own postlatch state. Resume and opcode selection dispatch to their phase; subsequent cycle and
register operations take direct goto case edges.
The immutable suspension/vector tests independently check the resulting code.
"""
from pathlib import Path
import hashlib
import sys
ROOT = Path(__file__).resolve().parent.parent
source = (ROOT / "SNESEmulator.Core/Spc700.cs").read_text(encoding="utf-8-sig")
decoder = source[source.index("    private void Execute()"):source.index("    private void Store(")]
EXPECTED_DECODER_SHA256 = "a071c87c7b6b21526d7ffe1f19f35c13b2e5e3bce213015eff051dbc3f4cb498"
if hashlib.sha256(decoder.encode()).hexdigest() != EXPECTED_DECODER_SHA256:
    raise SystemExit("Legacy SPC decoder changed: review hot microprograms and their independent oracles before regenerating")

def read(address, after=""):
    return ("read", address, "0", after)

def write(address, value):
    return ("write", address, value, "")

def idle():
    return ("wait", "null", "null", "")

def fetch(after):
    # Fetch increments PC only after its read/postlatch suspension has resumed.
    return read("PC", "PC++; " + after)

# The values are explicit cycle/register microprograms for the measured common
# forms. Unlisted opcodes are deliberately not duplicated here.
programs = {
    0x2f: [fetch("hotOperand0 = (sbyte)hotRead;"), idle(), idle(),
           "PC = (ushort)(PC + hotOperand0);"],
    0x8f: [fetch("hotOperand0 = hotRead;"), fetch("hotOperand1 = D(hotRead);"),
           read("(ushort)hotOperand1"), write("(ushort)hotOperand1", "(byte)hotOperand0")],
    0x65: ["hotOperand1 = A;", fetch("hotOperand0 = hotRead;"),
           fetch("hotOperand0 |= hotRead << 8;"),
           read("(ushort)hotOperand0", "Compare(hotOperand1, hotRead);")],
    0xaa: [fetch("hotOperand0 = hotRead;"),
           fetch("hotOperand0 |= hotRead << 8; hotOperand1 = 1 << (hotOperand0 >> 13); hotOperand0 &= 8191;"),
           read("(ushort)hotOperand0", "Flag(1, (hotRead & hotOperand1) != 0);")],
}
for opcode, register in [(0xe8, "A"), (0xcd, "X"), (0x8d, "Y")]:
    programs[opcode] = [fetch(register + " = NZ(hotRead);")]
for opcode, register in [(0xe4, "A"), (0xf8, "X"), (0xeb, "Y")]:
    programs[opcode] = [fetch("hotOperand0 = D(hotRead);"),
                        read("(ushort)hotOperand0", register + " = NZ(hotRead);")]
for opcode, register in [(0xc4, "A"), (0xd8, "X"), (0xcb, "Y")]:
    programs[opcode] = [fetch("hotOperand0 = D(hotRead); hotOperand1 = " + register + ";"),
                        read("(ushort)hotOperand0"), write("(ushort)hotOperand0", "(byte)hotOperand1")]
for opcode, condition in [(0x10, "!F(128)"), (0x30, "F(128)"), (0x50, "!F(64)"),
                          (0x70, "F(64)"), (0x90, "!F(1)"), (0xb0, "F(1)"),
                          (0xd0, "!F(2)"), (0xf0, "F(2)")]:
    # Branch condition is evaluated before fetching its signed displacement.
    programs[opcode] = ["hotBranchTaken = " + condition + ";",
                        fetch("hotOperand0 = (sbyte)hotRead;"), "BRANCH_NOT_TAKEN",
                        idle(), idle(), "PC = (ushort)(PC + hotOperand0);"]
for opcode, mask in [(0xd2, 64), (0xf2, 128)]:
    programs[opcode] = [fetch("hotOperand0 = D(hotRead);"),
                        read("(ushort)hotOperand0", "hotOperand1 = hotRead & ~" + str(mask) + ";"),
                        write("(ushort)hotOperand0", "(byte)hotOperand1")]

names = {0x2f:"BRA",0x10:"BPL",0x30:"BMI",0x50:"BVC",0x70:"BVS",0x90:"BCC",0xb0:"BCS",0xd0:"BNE",0xf0:"BEQ",0xe8:"MOV A,#imm",0xcd:"MOV X,#imm",0x8d:"MOV Y,#imm",0xe4:"MOV A,dp",0xf8:"MOV X,dp",0xeb:"MOV Y,dp",0xc4:"MOV dp,A",0xd8:"MOV dp,X",0xcb:"MOV dp,Y",0x8f:"MOV dp,#imm",0x65:"CMP A,abs",0xaa:"MOV1 C,mem.bit",0xd2:"CLR1 dp.6",0xf2:"CLR1 dp.7"}
def expression(text):
    return text

def statements(text):
    return [statement.strip() + ";" for statement in text.split(";") if statement.strip()]

lines = ["// <auto-generated> tools/generate-spc-hotpath.py; do not edit by hand.",
         "// Reviewed decoder SHA256: " + EXPECTED_DECODER_SHA256,
         "// 23 common forms; every remaining opcode uses the original decoder.",
         "// </auto-generated>", "namespace SNESEmulator.Core;", "", "public sealed partial class Spc700", "{",
         "    private bool ResumeHotInstruction()", "    {",
         "        // Resume/opcode selection dispatches to a phase. Direct edges avoid",
         "        // repeating sparse lookup for each cycle or register assignment.",
         "        while (true) switch (hotPhase)", "        {",
         "            case 0: // Opcode read; PC++ belongs to its postlatch state.",
         "                if (!TryHotCycle(PC, 0, \"read\", 1)) return false;", "                goto case 1;",
         "            case 1:", "                PC++;", "                switch (hotRead)", "                {"]
for op in sorted(programs):
    lines.append(f"                    case 0x{op:02x}: hotPhase = {1024+op*32}; break; // {names[op]}")
lines += ["                    default:", "                        // Opcode read is already journaled; the legacy decoder",
          "                        // reconstructs it without repeating bus/observer effects.",
          "                        hotPhase = -1; hotLegacy = true; cooperative = false;",
          "                        return RunLegacyContinuation();", "                }", "                continue;"]
for op in sorted(programs):
    state=1024+op*32
    lines += ["", f"            // {op:02X}: {names[op]}"]
    for micro in programs[op]:
        if isinstance(micro,str):
            text = "if (!hotBranchTaken) return FinishHotInstruction();" if micro == "BRANCH_NOT_TAKEN" else micro
            lines += [f"            case {state}:"]
            lines += ["                " + statement for statement in statements(text)]
            lines += [f"                hotPhase = {state+1}; goto case {state+1};"]
            state+=1
        else:
            direction,address,value,post=micro
            lines += [f"            case {state}: // {direction} admission/effect",
                      f"                if (!TryHotCycle({expression(address)}, {expression(value)}, \"{direction}\", {state+1})) return false;",
                      f"                goto case {state+1};",
                      f"            case {state+1}: // Resume after the latched effect"]
            if post: lines += ["                " + statement for statement in statements(post)]
            lines.append(f"                hotPhase = {state+2}; goto case {state+2};")
            state+=2
    lines += [f"            case {state}:", "                return FinishHotInstruction();"]
lines += ["            default: throw new InvalidOperationException(\"Invalid SPC hot-path phase\");", "        }", "    }", "}", ""]
output="\n".join(lines).replace('\\"','"')
target=ROOT/"SNESEmulator.Core/Spc700.HotPath.g.cs"
if "--check" in sys.argv:
    if not target.exists() or target.read_text(encoding="utf-8-sig")!=output:
        raise SystemExit("Generated SPC hot path differs; regenerate and rerun frozen/vector tests")
    print("SPC hot-path generator: exact match,23 forms")
else:
    target.write_text(output,encoding="utf-8")
