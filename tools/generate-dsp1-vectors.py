# Creates deterministic authored DSP1 numeric inputs and verifies frozen expected input bytes.
#

"""Reproduce authored input bytes without modifying any pinned fixture.

The raw set is the accuracy audit. A former constrained set and its RT derivative
are preserved only for provenance; neither converts the raw audit into a pass.
External expected outputs are never generated by this script.
"""
import argparse,gzip,pathlib,random,struct
ROOT=pathlib.Path(__file__).resolve().parents[1]
def records():
 rng=random.Random(0x772510);raw=[];constrained=[]
 for i in range(8192):
  r=[rng.randrange(65536) for _ in range(13)];r[3]&=255;r[4]&=1023;ram=[0]*256
  for j in {r[3],r[3]|64,rng.randrange(256)}:ram[j]=rng.randrange(65536)
  sr=rng.randrange(65536)&~0x7c;fa=rng.randrange(64);fb=rng.randrange(64)
  if i<6144:
   op=rng.randrange(1<<22);acc=(op>>15)&1
   if (op&15)==acc+1:op&=~15
  elif i<7168:op=0xc00000|rng.randrange(1<<22)
  else:
   c=rng.choice([0,0x100,0x101,0x140,0x141,*range(0x80,0xb0,2),*range(0xb0,0xb4),0xb4,0xb6,0xb8,0xba,0xbc,0xbe]);op=0x800000|(c<<13)|(rng.randrange(2048)<<2)
  raw.append(struct.pack('<I13H256HHBB',op,*r,*ram,sr,fa,fb))
  constrained.append(struct.pack('<I13H256HHBB',op,*r,*ram,sr&~0x1000 if sr&0x400 else sr,fa,fb))
 rt=[]
 for rec in constrained[:1024]:
  b=bytearray(rec);struct.pack_into('<I',b,0,struct.unpack_from('<I',b)[0]|0x400000);rt.append(b)
 return {'raw-inputs':raw,'inputs':constrained,'rt-inputs':rt}
def verify(root):
 for name,cases in records().items():
  actual=struct.pack('<I',len(cases))+b''.join(cases);expected=gzip.decompress((root/(name+'.bin.gz')).read_bytes())
  assert actual==expected,('Authored input reproduction differs',name)
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--root',type=pathlib.Path,default=ROOT/'testdata/dsp1');a=p.parse_args();verify(a.root);print('DSP1 authored raw/constrained historical input bytes reproduced; no expected data written')
